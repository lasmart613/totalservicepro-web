-- SECURITY DEFINER so SELECT policies can see teammate rows without recursion.
CREATE OR REPLACE FUNCTION public.my_membership_org_ids()
RETURNS SETOF bigint
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT organization_id
  FROM public.organization_memberships
  WHERE user_id = auth.uid();
$$;

DROP POLICY IF EXISTS organization_memberships_select_own ON public.organization_memberships;
CREATE POLICY organization_memberships_select_own ON public.organization_memberships
  FOR SELECT
  TO authenticated
  USING (
    user_id = auth.uid()
    OR organization_id IN (SELECT public.my_membership_org_ids())
  );

DROP POLICY IF EXISTS organization_memberships_insert_own_home ON public.organization_memberships;
CREATE POLICY organization_memberships_insert_own_home ON public.organization_memberships
  FOR INSERT
  TO authenticated
  WITH CHECK (
    user_id = auth.uid()
    AND (
      EXISTS (
        SELECT 1 FROM public.organizations o
        WHERE o.id = organization_id AND o.created_by = auth.uid()
      )
      OR EXISTS (
        SELECT 1 FROM public.engineer_invitations i
        WHERE i.organization_id = organization_id
          AND lower(i.email) = lower((SELECT email FROM public.user_profiles WHERE id = auth.uid()))
          AND COALESCE(i.accepted, false) = false
      )
    )
  );

DROP POLICY IF EXISTS organization_memberships_delete_own ON public.organization_memberships;
CREATE POLICY organization_memberships_delete_own ON public.organization_memberships
  FOR DELETE
  TO authenticated
  USING (user_id = auth.uid() AND is_home = false);

