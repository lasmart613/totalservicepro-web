SELECT m.id,
       'pending',
       CASE
         WHEN lower(coalesce(m.model, '') || ' ' || coalesce(m.title, '')) ~ 'vpyag|vp-yag|vp yag|mini gentle ?yag'
           THEN 0
         WHEN lower(coalesce(m.brand, '')) = 'candela' THEN 10
         ELSE 100
       END
  FROM public.manuals m
ON CONFLICT (manual_id) DO NOTHING;


