-- 000940: CRM > customer > "Send email" (per-user mailbox OAuth + send log + rate cap).
--
-- New objects (all COMMENTed '000940 ...' so the rollback can prove ownership):
--   * public.user_mailbox_connections: one row per (user, provider) with the
--     OAuth refresh token ENCRYPTED by the web server (AES-256-GCM, key in the
--     Netlify env MAILBOX_TOKEN_KEY). The database never sees plaintext tokens.
--     RLS on, NO policies, and only service_role has privileges. anon and
--     authenticated have nothing (no default privileges are relied on).
--   * public.customer_email_sends: the customer timeline log for each send
--     (who, which customer, recipient, subject, transport, status). RLS on.
--     authenticated may SELECT rows of an org they are an active member of
--     (customer timeline). Only service_role writes, through the functions below.
--   * public.customer_email_reserve_send(...): atomic per-user rate cap
--     (20 per rolling hour, 100 per rolling day; pending + sent count, failed
--     does not). Takes a per-user advisory xact lock, so two parallel sends
--     cannot both slip under the cap. Inserts a 'pending' row and returns it.
--   * public.customer_email_finish_send(id, status, message_id, error):
--     marks the reserved row 'sent' or 'failed' (only from 'pending').
--   Both functions: SECURITY DEFINER, SET search_path = '', EXECUTE for
--   service_role only (revoked from PUBLIC, anon, authenticated).
--
-- No existing table, policy, grant or row is changed. Re-runnable.

BEGIN;

SET LOCAL lock_timeout = '5s';

-- Drift guards: refuse if a same-named object exists that 000940 did not make,
-- or if the tables 000940 depends on are missing.
DO $$
BEGIN
  IF to_regclass('public.organizations') IS NULL
     OR to_regclass('public.organization_customers') IS NULL
     OR to_regclass('public.organization_memberships') IS NULL THEN
    RAISE EXCEPTION '000940: organizations / organization_customers / organization_memberships missing';
  END IF;
  IF to_regprocedure('public.is_active_org_member(bigint)') IS NULL THEN
    RAISE EXCEPTION '000940: public.is_active_org_member(bigint) missing';
  END IF;
  IF to_regclass('public.user_mailbox_connections') IS NOT NULL
     AND coalesce(obj_description(to_regclass('public.user_mailbox_connections'), 'pg_class'), '') NOT LIKE '000940%' THEN
    RAISE EXCEPTION '000940: public.user_mailbox_connections exists and was not created by 000940';
  END IF;
  IF to_regclass('public.customer_email_sends') IS NOT NULL
     AND coalesce(obj_description(to_regclass('public.customer_email_sends'), 'pg_class'), '') NOT LIKE '000940%' THEN
    RAISE EXCEPTION '000940: public.customer_email_sends exists and was not created by 000940';
  END IF;
  IF EXISTS (
    SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
    WHERE n.nspname = 'public'
      AND p.proname IN ('customer_email_reserve_send', 'customer_email_finish_send')
      AND coalesce(obj_description(p.oid, 'pg_proc'), '') NOT LIKE '000940%') THEN
    RAISE EXCEPTION '000940: a customer_email_* function exists and was not created by 000940';
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS public.user_mailbox_connections (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users (id) ON DELETE CASCADE,
  provider text NOT NULL CHECK (provider IN ('microsoft', 'google')),
  email text NOT NULL CHECK (length(email) BETWEEN 3 AND 320),
  refresh_token_enc text NOT NULL CHECK (refresh_token_enc LIKE 'v1.%'),
  scopes text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  last_used_at timestamptz,
  last_error text,
  CONSTRAINT user_mailbox_connections_user_provider_key UNIQUE (user_id, provider)
);
COMMENT ON TABLE public.user_mailbox_connections IS
  '000940: per-user Connect mailbox (Microsoft Graph Mail.Send / Gmail gmail.send). refresh_token_enc is AES-256-GCM ciphertext made by the web server (MAILBOX_TOKEN_KEY). service_role only.';

ALTER TABLE public.user_mailbox_connections ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.user_mailbox_connections FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.user_mailbox_connections TO service_role;
DO $$
BEGIN
  IF to_regclass('public.user_mailbox_connections_id_seq') IS NOT NULL THEN
    REVOKE ALL ON SEQUENCE public.user_mailbox_connections_id_seq FROM PUBLIC, anon, authenticated;
    GRANT USAGE, SELECT ON SEQUENCE public.user_mailbox_connections_id_seq TO service_role;
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS public.customer_email_sends (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  service_organization_id bigint NOT NULL REFERENCES public.organizations (id) ON DELETE CASCADE,
  customer_organization_id bigint NOT NULL REFERENCES public.organizations (id) ON DELETE CASCADE,
  sender_user_id uuid REFERENCES auth.users (id) ON DELETE SET NULL,
  sender_name text,
  sender_email text,
  recipient_email text NOT NULL CHECK (length(recipient_email) BETWEEN 3 AND 320),
  subject text NOT NULL CHECK (length(subject) BETWEEN 1 AND 300),
  audience text CHECK (audience IS NULL OR audience IN ('clinic', 'repair_shop', 'rental_shop', 'custom')),
  transport text NOT NULL CHECK (transport IN ('microsoft', 'google', 'resend')),
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'sent', 'failed')),
  provider_message_id text,
  error text,
  created_at timestamptz NOT NULL DEFAULT now(),
  finished_at timestamptz
);
COMMENT ON TABLE public.customer_email_sends IS
  '000940: CRM customer timeline log of Send email. Written only by customer_email_reserve_send / customer_email_finish_send (service_role).';
CREATE INDEX IF NOT EXISTS customer_email_sends_sender_created_idx
  ON public.customer_email_sends (sender_user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS customer_email_sends_customer_idx
  ON public.customer_email_sends (service_organization_id, customer_organization_id, created_at DESC);
COMMENT ON INDEX public.customer_email_sends_sender_created_idx IS '000940: rate cap lookups';
COMMENT ON INDEX public.customer_email_sends_customer_idx IS '000940: customer timeline';

ALTER TABLE public.customer_email_sends ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.customer_email_sends FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE public.customer_email_sends TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.customer_email_sends TO service_role;
DO $$
BEGIN
  IF to_regclass('public.customer_email_sends_id_seq') IS NOT NULL THEN
    REVOKE ALL ON SEQUENCE public.customer_email_sends_id_seq FROM PUBLIC, anon, authenticated;
    GRANT USAGE, SELECT ON SEQUENCE public.customer_email_sends_id_seq TO service_role;
  END IF;
END $$;

DROP POLICY IF EXISTS customer_email_sends_member_select ON public.customer_email_sends;
CREATE POLICY customer_email_sends_member_select ON public.customer_email_sends
  FOR SELECT TO authenticated
  USING (public.is_active_org_member(service_organization_id));
COMMENT ON POLICY customer_email_sends_member_select ON public.customer_email_sends IS
  '000940: members of the sending org see their org''s customer email log';

CREATE OR REPLACE FUNCTION public.customer_email_reserve_send(
  p_sender uuid,
  p_service_org bigint,
  p_customer_org bigint,
  p_recipient text,
  p_subject text,
  p_audience text,
  p_transport text,
  p_sender_name text,
  p_sender_email text,
  p_hour_cap integer DEFAULT 20,
  p_day_cap integer DEFAULT 100
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $fn$
DECLARE
  v_hour integer;
  v_day integer;
  v_id bigint;
BEGIN
  IF p_sender IS NULL OR p_service_org IS NULL OR p_customer_org IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'code', 'invalid_request');
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM public.organization_memberships m
    WHERE m.user_id = p_sender AND m.organization_id = p_service_org) THEN
    RETURN jsonb_build_object('ok', false, 'code', 'not_member');
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM public.organization_customers c
    WHERE c.service_organization_id = p_service_org AND c.customer_organization_id = p_customer_org) THEN
    RETURN jsonb_build_object('ok', false, 'code', 'not_customer');
  END IF;

  -- One sender at a time, so parallel sends cannot both pass the cap.
  PERFORM pg_catalog.pg_advisory_xact_lock(940, pg_catalog.hashtext(p_sender::text));

  SELECT count(*) FILTER (WHERE s.created_at > pg_catalog.now() - interval '1 hour'),
         count(*)
    INTO v_hour, v_day
    FROM public.customer_email_sends s
   WHERE s.sender_user_id = p_sender
     AND s.status IN ('pending', 'sent')
     AND s.created_at > pg_catalog.now() - interval '1 day';

  IF v_hour >= LEAST(GREATEST(coalesce(p_hour_cap, 20), 0), 20) THEN
    RETURN jsonb_build_object('ok', false, 'code', 'rate_limited_hour', 'hour', v_hour, 'day', v_day);
  END IF;
  IF v_day >= LEAST(GREATEST(coalesce(p_day_cap, 100), 0), 100) THEN
    RETURN jsonb_build_object('ok', false, 'code', 'rate_limited_day', 'hour', v_hour, 'day', v_day);
  END IF;

  INSERT INTO public.customer_email_sends (
    service_organization_id, customer_organization_id, sender_user_id, sender_name, sender_email,
    recipient_email, subject, audience, transport, status)
  VALUES (
    p_service_org, p_customer_org, p_sender, left(p_sender_name, 200), left(p_sender_email, 320),
    p_recipient, left(p_subject, 300), p_audience, p_transport, 'pending')
  RETURNING id INTO v_id;

  RETURN jsonb_build_object('ok', true, 'id', v_id, 'hour', v_hour + 1, 'day', v_day + 1);
END;
$fn$;
COMMENT ON FUNCTION public.customer_email_reserve_send(uuid, bigint, bigint, text, text, text, text, text, text, integer, integer) IS
  '000940: per-user rate cap (20/hour, 100/day; callers can only lower it) + pending log row. service_role only.';

CREATE OR REPLACE FUNCTION public.customer_email_finish_send(
  p_id bigint,
  p_status text,
  p_provider_message_id text,
  p_error text
) RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $fn$
DECLARE
  v_n integer;
BEGIN
  IF p_status NOT IN ('sent', 'failed') THEN
    RAISE EXCEPTION 'customer_email_finish_send: bad status %', p_status USING ERRCODE = '22023';
  END IF;
  UPDATE public.customer_email_sends
     SET status = p_status,
         provider_message_id = left(p_provider_message_id, 300),
         error = left(p_error, 500),
         finished_at = pg_catalog.now()
   WHERE id = p_id AND status = 'pending';
  GET DIAGNOSTICS v_n = ROW_COUNT;
  RETURN v_n = 1;
END;
$fn$;
COMMENT ON FUNCTION public.customer_email_finish_send(bigint, text, text, text) IS
  '000940: mark a reserved customer email sent/failed. service_role only.';

REVOKE ALL ON FUNCTION public.customer_email_reserve_send(uuid, bigint, bigint, text, text, text, text, text, text, integer, integer) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.customer_email_finish_send(bigint, text, text, text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.customer_email_reserve_send(uuid, bigint, bigint, text, text, text, text, text, text, integer, integer) TO service_role;
GRANT EXECUTE ON FUNCTION public.customer_email_finish_send(bigint, text, text, text) TO service_role;

COMMIT;
