CREATE OR REPLACE FUNCTION public.auth_login_email() RETURNS text
LANGUAGE sql STABLE SET search_path = '' AS $$
  SELECT nullif(pg_catalog.current_setting('request.jwt.claim.email', true), '')
$$;

CREATE OR REPLACE FUNCTION public.invitation_is_open(
  p_accepted boolean,
  p_expires_at timestamptz,
  p_created_at timestamptz
) RETURNS boolean
LANGUAGE sql STABLE SET search_path = '' AS $$
  SELECT coalesce(p_accepted, false) = false
    AND (
      (p_expires_at IS NOT NULL AND p_expires_at > pg_catalog.now())
      OR (
        p_expires_at IS NULL
        AND p_created_at IS NOT NULL
        AND p_created_at > (pg_catalog.now() - interval '14 days')
      )
    );
$$;

CREATE OR REPLACE FUNCTION public.profile_role_from_membership(p_role text) RETURNS text
LANGUAGE sql IMMUTABLE SET search_path = '' AS $$
  SELECT CASE
    WHEN lower(pg_catalog.btrim(coalesce(p_role, ''))) = 'admin' THEN 'company_admin'
    WHEN nullif(pg_catalog.btrim(p_role), '') IS NULL THEN 'fse'
    ELSE pg_catalog.btrim(p_role)
  END;
$$;

CREATE OR REPLACE FUNCTION public.org_unclaimed_new(p_org bigint, p_created_at timestamptz)
RETURNS boolean
LANGUAGE sql STABLE SET search_path = '' AS $$
  SELECT p_org IS NOT NULL
    AND p_created_at IS NOT NULL
    AND p_created_at > pg_catalog.now() - interval '24 hours'
    AND NOT EXISTS (
      SELECT 1 FROM public.organization_memberships m WHERE m.organization_id = p_org
    );
$$;

CREATE OR REPLACE FUNCTION public.org_founder_claim_allowed(p_org bigint)
RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.organizations o
    WHERE o.id = p_org AND public.org_unclaimed_new(o.id, o.created_at)
  );
$$;

CREATE OR REPLACE FUNCTION public.founder_role_for_org(p_organization_id bigint)
RETURNS text
LANGUAGE sql STABLE SET search_path = '' AS $$
  SELECT 'company_admin'::text;
$$;

