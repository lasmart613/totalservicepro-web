-- Service role: expiry/removal clears the premium fields and leaves
-- trial_granted_at; the founder route can still set it on a grant.
DO $$
DECLARE
  kept timestamptz;
BEGIN
  PERFORM set_config('role', 'service_role', true);
  UPDATE public.organizations
     SET is_premium = false, premium_until = NULL, premium_grant = NULL
   WHERE id = 1;
  SELECT trial_granted_at INTO kept FROM public.organizations WHERE id = 1;
  IF kept IS DISTINCT FROM timestamptz '2026-10-01 10:00+00' THEN
    RAISE EXCEPTION 'FAIL expiry changed trial_granted_at to %', kept;
  END IF;

  UPDATE public.organizations
     SET is_premium = true, premium_until = now() + interval '60 days',
         premium_grant = 'complimentary_signup', trial_granted_at = now()
   WHERE id = 7 AND trial_granted_at IS NULL;
  IF NOT FOUND THEN RAISE EXCEPTION 'FAIL service role could not grant with trial_granted_at'; END IF;

  -- The founder route's conditional write does not land twice.
  UPDATE public.organizations SET premium_grant = 'complimentary_signup'
   WHERE id = 7 AND trial_granted_at IS NULL;
  IF FOUND THEN RAISE EXCEPTION 'FAIL conditional grant landed on a used trial'; END IF;

  PERFORM set_config('role', 'postgres', true);
END $$;

