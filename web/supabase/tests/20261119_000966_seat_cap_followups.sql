  BEGIN
    INSERT INTO public.organization_memberships (user_id, organization_id, role, is_home)
    VALUES ('00000000-0000-4000-8000-000000008851', 8814, 'fse', false);
    RAISE EXCEPTION 'stranger insert into an open org was allowed';
  EXCEPTION
    WHEN insufficient_privilege THEN open_msg := SQLERRM;
  END;
  BEGIN
    INSERT INTO public.organization_memberships (user_id, organization_id, role, is_home)
    VALUES ('00000000-0000-4000-8000-000000008851', 8801, 'fse', false);
    RAISE EXCEPTION 'stranger insert into a full org was allowed';
  EXCEPTION
    WHEN insufficient_privilege THEN full_msg := SQLERRM;
  END;
  IF open_msg IS NULL OR full_msg IS DISTINCT FROM open_msg THEN
    RAISE EXCEPTION 'stranger denials differ (open %, full %)', open_msg, full_msg;
  END IF;
  IF open_msg ~ '[0-9]' OR open_msg ILIKE '%upgrade%' OR open_msg ILIKE '%team%'
     OR open_msg ILIKE '%using % of %' OR open_msg ILIKE '%contact us%' THEN
    RAISE EXCEPTION 'stranger denial names the cap: %', open_msg;
  END IF;
  RAISE NOTICE 'ok   stranger denial is the same under the cap and at the cap';
END $$;
ROLLBACK;

