CREATE FUNCTION pg_temp.main_claim_body(u text, org bigint, email text) RETURNS text LANGUAGE sql AS $$
  SELECT pg_temp.as_service(format($q$WITH p AS (
      INSERT INTO public.user_profiles (id, email, role, organization_id, onboarding_completed)
      VALUES (%L, %L, 'owner', %s, true)
      ON CONFLICT (id) DO UPDATE SET role = 'owner', organization_id = EXCLUDED.organization_id, onboarding_completed = true
