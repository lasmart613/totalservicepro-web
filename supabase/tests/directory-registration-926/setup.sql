-- Schema fingerprint: public functions (+ACL), policies, relations (+ACL),
-- columns, constraints, indexes, and every user trigger (auth.users too).
CREATE FUNCTION pg_temp.fingerprint() RETURNS text LANGUAGE sql AS $$
  SELECT md5(
    COALESCE((SELECT string_agg(p.oid::regprocedure::text || ':' || md5(pg_get_functiondef(p.oid)) || ':' || COALESCE((SELECT string_agg(a::text, ',' ORDER BY a::text) FROM unnest(p.proacl) a), ''), '|' ORDER BY p.oid::regprocedure::text)
       FROM pg_proc p WHERE p.pronamespace = 'public'::regnamespace AND p.prokind = 'f'), '')
    || '#' ||
    COALESCE((SELECT string_agg(tablename || '.' || policyname || ':' || cmd || ':' || COALESCE(qual, '') || ':' || COALESCE(with_check, '') || ':' || roles::text, '|' ORDER BY tablename, policyname)
       FROM pg_policies WHERE schemaname = 'public'), '')
    || '#' ||
    COALESCE((SELECT string_agg(c.relname || ':' || c.relkind::text || ':' || COALESCE(c.relacl::text, ''), ',' ORDER BY c.relname) FROM pg_class c WHERE c.relnamespace = 'public'::regnamespace), '')
    || '#' ||
    COALESCE((SELECT string_agg(c.relname || '.' || a.attname || ':' || format_type(a.atttypid, a.atttypmod) || ':' || a.attnotnull::text, ',' ORDER BY c.relname, a.attnum)
       FROM pg_attribute a JOIN pg_class c ON c.oid = a.attrelid
       WHERE c.relnamespace = 'public'::regnamespace AND c.relkind = 'r' AND a.attnum > 0 AND NOT a.attisdropped), '')
    || '#' ||
    COALESCE((SELECT string_agg(conrelid::regclass::text || '.' || conname || ':' || pg_get_constraintdef(oid), '|' ORDER BY conrelid::regclass::text, conname)
       FROM pg_constraint WHERE connamespace = 'public'::regnamespace), '')
    || '#' ||
    COALESCE((SELECT string_agg(indexrelid::regclass::text || ':' || pg_get_indexdef(indexrelid), '|' ORDER BY indexrelid::regclass::text)
       FROM pg_index i JOIN pg_class c ON c.oid = i.indrelid WHERE c.relnamespace = 'public'::regnamespace), '')
    || '#' ||
