CREATE FUNCTION pg_temp.run(u text, r text, stmt text) RETURNS text LANGUAGE plpgsql AS $$
DECLARE t text;
BEGIN
  PERFORM set_config('request.jwt.claim.sub', coalesce(u, ''), true);
  EXECUTE format('SET LOCAL ROLE %I', r);
  BEGIN
    EXECUTE stmt INTO t;
    t := 'OK ' || COALESCE(t, '(null)');
  EXCEPTION WHEN others THEN
    t := 'ERR ' || SQLSTATE;
  END;
  EXECUTE 'RESET ROLE';
  PERFORM set_config('request.jwt.claim.sub', '', true);
  RETURN t;
END $$;
CREATE FUNCTION pg_temp.as_user(u text, stmt text) RETURNS text LANGUAGE sql AS $$ SELECT pg_temp.run(u, 'authenticated', stmt) $$;
CREATE FUNCTION pg_temp.as_service(stmt text) RETURNS text LANGUAGE sql AS $$ SELECT pg_temp.run(NULL, 'service_role', stmt) $$;
CREATE FUNCTION pg_temp.as_anon(stmt text) RETURNS text LANGUAGE sql AS $$ SELECT pg_temp.run(NULL, 'anon', stmt) $$;
CREATE FUNCTION pg_temp.expect(label text, got text, want text) RETURNS void LANGUAGE plpgsql AS $$
BEGIN
  IF got IS DISTINCT FROM want THEN RAISE EXCEPTION '% FAILED: got %, want %', label, got, want; END IF;
  RAISE NOTICE 'PASS %', label;
END $$;
